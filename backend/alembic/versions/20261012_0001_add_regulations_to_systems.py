def _generate_uuid() -> str:
    return str(uuid.uuid4())


def _dict_categories_table() -> sa.Table:
    return sa.table(
        "dict_categories",
        sa.column("id", sa.String),
        sa.column("code", sa.String),
        sa.column("name", sa.String),
        sa.column("description", sa.Text),
        sa.column("is_system", sa.Boolean),
        sa.column("created_at", sa.DateTime),
    )


def _dict_items_table() -> sa.Table:
    return sa.table(
        "dict_items",
        sa.column("id", sa.String),
        sa.column("category_id", sa.String),
        sa.column("code", sa.String),
        sa.column("label", sa.String),
        sa.column("description", sa.Text),
        sa.column("sort_order", sa.Integer),
        sa.column("is_enabled", sa.Boolean),
        sa.column("extra", sa.String),
        sa.column("permission_profile", sa.String),
        sa.column("permission_codes", sa.JSON),
        sa.column("created_at", sa.DateTime),
    )


def _has_regulations_column(bind) -> bool:
    inspector = sa.inspect(bind)
    return "regulations" in [c["name"] for c in inspector.get_columns("systems")]


